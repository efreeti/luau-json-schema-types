"""Translate JSON snapshots into ordinary, statically checked Luau tables."""
from pathlib import Path
import json, re
root = Path(__file__).resolve().parents[1]
def literal(value):
    if value is None:
        return 'nil'  # Native projection: nil fields/entries cannot preserve JSON null.
    if value is True: return 'true'
    if value is False: return 'false'
    if isinstance(value, str):
        return '"' + ''.join(
            re.sub(r'\\u([0-9a-fA-F]{4})', lambda match: r'\u{' + match[1] + '}',
                   json.dumps(char, ensure_ascii=False)[1:-1])
            for char in value
        ) + '"'
    if isinstance(value, (int, float)): return repr(value)
    if isinstance(value, list): return '{ ' + ', '.join(literal(item) for item in value) + ' }'
    return '{ ' + ', '.join('[' + literal(key) + '] = ' + literal(item) for key, item in value.items()) + ' }'
lines = ['--!strict', '-- Generated by scripts/generate-fixtures.py; do not edit.', 'local Types = require("../src")', 'local fixtures: { { name: string, schema: Types.JSONSchema } } = {']
for path in sorted((root / 'tests/fixtures').rglob('*.json')):
    lines.append('    { name = ' + literal(path.relative_to(root / 'tests/fixtures').as_posix()) + ', schema = ' + literal(json.loads(path.read_text())) + ' },')
lines.extend(['}', 'return fixtures'])
(root / 'tests/FixtureData.luau').write_text('\n'.join(lines) + '\n')
